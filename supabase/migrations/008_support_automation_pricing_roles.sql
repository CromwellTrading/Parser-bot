-- SynthesisOne product additions: client support inbox, automation availability,
-- per-session initial/renewal pricing and persisted payment price snapshots.
-- Execute in the Supabase SQL Editor before deploying this backend version.

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  client_id text not null,
  sender_role text not null check (sender_role in ('client', 'admin')),
  message text not null check (char_length(message) between 1 and 4000),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists support_messages_client_created_idx
  on public.support_messages (client_id, created_at asc);
create index if not exists support_messages_unread_idx
  on public.support_messages (client_id, sender_role, read_at)
  where read_at is null;

create table if not exists public.synthesisone_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
insert into public.synthesisone_settings (key, value, updated_at)
values (
  'automation_availability',
  '{"enabled": true, "message": "La automatización está disponible."}'::jsonb,
  now()
)
on conflict (key) do nothing;

alter table public.license_activation_sessions
  add column if not exists price_amount numeric,
  add column if not exists price_type text;

-- Existing pending sessions receive the current business pricing snapshot.
-- Returning numbers are identified by an existing client license for that phone.
update public.license_activation_sessions s
set
  price_amount = case when exists (
    select 1 from public.clients c
    where c.phone_number = s.phone_number and c.role = 'client'
  ) then 10000 else 28000 end,
  price_type = case when exists (
    select 1 from public.clients c
    where c.phone_number = s.phone_number and c.role = 'client'
  ) then 'renewal' else 'initial' end
where s.price_amount is null or s.price_type is null;

